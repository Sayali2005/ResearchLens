import React, { useState, useEffect } from 'react';
import {
  Bookmark,
  Trash2,
  ArrowRight,
  BookOpen,
  ExternalLink,
  Download,
  Printer,
  Sparkles,
  FileText,
  Copy,
  Check,
  Grid3X3,
  AlertCircle,
} from 'lucide-react';
import { Link } from 'react-router-dom';
import { PaperDrawer } from '../components/PaperDrawer';

export function SavedPage() {
  const [savedTopics, setSavedTopics] = useState([]);
  const [savedPapers, setSavedPapers] = useState([]);
  const [savedGaps, setSavedGaps] = useState([]);
  const [activeTab, setActiveTab] = useState('papers'); // 'papers' | 'gaps' | 'topics'
  const [selectedPaper, setSelectedPaper] = useState(null);
  const [copiedBibId, setCopiedBibId] = useState(null);

  useEffect(() => {
    try {
      const topics = JSON.parse(localStorage.getItem('researchlens_saved_topics') || '[]');
      const papers = JSON.parse(localStorage.getItem('researchlens_saved_papers') || '[]');
      const gaps = JSON.parse(localStorage.getItem('researchlens_saved_gaps') || '[]');
      setSavedTopics(topics);
      setSavedPapers(papers);
      setSavedGaps(gaps);
    } catch {
      // fallback
    }
  }, []);

  const removeTopic = (id) => {
    const updated = savedTopics.filter((t) => t.id !== id);
    setSavedTopics(updated);
    localStorage.setItem('researchlens_saved_topics', JSON.stringify(updated));
  };

  const removePaper = (id) => {
    const updated = savedPapers.filter((p) => p.id !== id);
    setSavedPapers(updated);
    localStorage.setItem('researchlens_saved_papers', JSON.stringify(updated));
  };

  const removeGap = (key) => {
    const updated = savedGaps.filter((g) => g.key !== key);
    setSavedGaps(updated);
    localStorage.setItem('researchlens_saved_gaps', JSON.stringify(updated));
  };

  const handleCopyBibtex = (paper) => {
    const firstAuthor = paper.authors && paper.authors[0]
      ? (typeof paper.authors[0] === 'string' ? paper.authors[0] : paper.authors[0].name).split(' ').pop().toLowerCase()
      : 'author';
    const year = paper.year || '2024';
    const key = `${firstAuthor}${year}${paper.id ? paper.id.slice(-4) : 'cite'}`;
    const authorNames = (paper.authors || []).map((a) => (typeof a === 'string' ? a : a.name)).join(', ');
    const bibtex = `@article{${key},
  title={${paper.title}},
  author={${authorNames}},
  journal={${paper.venue || 'ResearchLens Corpus'}},
  year={${year}},
  doi={${paper.doi || ''}}
}`;
    navigator.clipboard.writeText(bibtex);
    setCopiedBibId(paper.id);
    setTimeout(() => setCopiedBibId(null), 2000);
  };

  const handleExportJSON = () => {
    const payload = {
      exported_at: new Date().toISOString(),
      project_title: 'Personal Research Dossier',
      topics: savedTopics,
      papers: savedPapers,
      gaps: savedGaps,
    };
    const blob = new Blob([JSON.stringify(payload, null, 2)], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `research_dossier_${new Date().toISOString().slice(0, 10)}.json`;
    a.click();
  };

  const handleExportMarkdown = () => {
    let md = `# Personal Research Dossier & Project Basket\n\nGenerated by ResearchLens on ${new Date().toLocaleDateString()}\n\n`;

    if (savedTopics.length > 0) {
      md += `## 1. Focal Research Domains\n`;
      savedTopics.forEach((t) => {
        md += `- **${t.name}** (Saved on ${new Date(t.savedAt).toLocaleDateString()})\n`;
      });
      md += `\n`;
    }

    if (savedGaps.length > 0) {
      md += `## 2. Identified Literature Voids & Opportunities\n`;
      savedGaps.forEach((g) => {
        md += `### ${g.topicName} × ${g.appName}\n`;
        md += `- **Domain**: ${g.domainName || g.domainId}\n`;
        md += `- **Observed Papers**: ${g.observed} (Expected: ${g.expected})\n`;
        md += `- **Opportunity Score**: ${(g.opportunity * 10).toFixed(1)}/10\n`;
        if (g.z_score !== undefined) md += `- **Poisson Significance Z-Score**: ${g.z_score}\n`;
        md += `\n`;
      });
    }

    if (savedPapers.length > 0) {
      md += `## 3. Curated Milestone Papers\n`;
      savedPapers.forEach((p, idx) => {
        const authors = (p.authors || []).map((a) => (typeof a === 'string' ? a : a.name)).join(', ');
        md += `${idx + 1}. **${p.title}** (${p.year || 'N/A'})\n`;
        md += `   - Authors: ${authors}\n`;
        md += `   - Venue: ${p.venue || 'N/A'} (Citations: ${p.citation_count || 0})\n`;
        if (p.pdf_url) md += `   - PDF: ${p.pdf_url}\n`;
        if (p.doi) md += `   - DOI: https://doi.org/${p.doi}\n`;
        if (p.arxiv_id) md += `   - arXiv: https://arxiv.org/abs/${p.arxiv_id}\n`;
        md += `\n`;
      });
    }

    const blob = new Blob([md], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `research_dossier_${new Date().toISOString().slice(0, 10)}.md`;
    a.click();
  };

  const totalItems = savedPapers.length + savedGaps.length + savedTopics.length;

  return (
    <div style={{ maxWidth: '1060px', margin: '0 auto', padding: '40px 24px 80px' }}>
      {/* Header & Export Controls */}
      <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', flexWrap: 'wrap', gap: '16px', marginBottom: '32px' }}>
        <div>
          <div style={{ display: 'flex', alignItems: 'center', gap: '8px', color: '#10B981', fontWeight: 600, fontSize: '0.85rem', marginBottom: '8px' }}>
            <Bookmark size={18} />
            <span>Personal Research Dossier</span>
          </div>
          <h1>My Research Project Basket</h1>
          <p style={{ color: 'var(--text-secondary)', fontSize: '1rem', marginTop: '6px' }}>
            Curate bookmark milestone literature, empirically validated research voids, and focal domains for thesis or grant proposals.
          </p>
        </div>

        {totalItems > 0 && (
          <div style={{ display: 'flex', gap: '8px', flexWrap: 'wrap' }}>
            <button className="btn btn-outline btn-sm" onClick={handleExportMarkdown}>
              <FileText size={14} />
              <span>Export Markdown</span>
            </button>
            <button className="btn btn-outline btn-sm" onClick={handleExportJSON}>
              <Download size={14} />
              <span>Export JSON</span>
            </button>
            <button className="btn btn-primary btn-sm" onClick={() => window.print()}>
              <Printer size={14} />
              <span>Print / PDF</span>
            </button>
          </div>
        )}
      </div>

      {/* Tabs */}
      <div style={{ display: 'flex', gap: '8px', borderBottom: '1px solid var(--border-color)', paddingBottom: '12px', marginBottom: '24px' }}>
        <button
          className={`btn btn-sm ${activeTab === 'papers' ? 'btn-primary' : 'btn-subtle'}`}
          onClick={() => setActiveTab('papers')}
        >
          <FileText size={14} />
          <span>Milestone Papers ({savedPapers.length})</span>
        </button>
        <button
          className={`btn btn-sm ${activeTab === 'gaps' ? 'btn-primary' : 'btn-subtle'}`}
          onClick={() => setActiveTab('gaps')}
        >
          <Grid3X3 size={14} />
          <span>Literature Gaps ({savedGaps.length})</span>
        </button>
        <button
          className={`btn btn-sm ${activeTab === 'topics' ? 'btn-primary' : 'btn-subtle'}`}
          onClick={() => setActiveTab('topics')}
        >
          <Bookmark size={14} />
          <span>Saved Domains ({savedTopics.length})</span>
        </button>
      </div>

      {/* Tab 1: Bookmarked Papers */}
      {activeTab === 'papers' && (
        <div>
          {savedPapers.length === 0 ? (
            <div className="panel" style={{ textAlign: 'center', padding: '48px 24px' }}>
              <FileText size={36} color="var(--text-muted)" style={{ margin: '0 auto 12px' }} />
              <h3>No Bookmarked Papers Yet</h3>
              <p style={{ color: 'var(--text-secondary)', marginTop: '6px', maxWidth: '420px', margin: '6px auto 16px' }}>
                Use the "Save" ⭐ button on any paper card in the Papers view to build your literature review corpus.
              </p>
              <Link to="/" className="btn btn-primary btn-sm">Explore Research Domains</Link>
            </div>
          ) : (
            <div style={{ display: 'flex', flexDirection: 'column', gap: '14px' }}>
              {savedPapers.map((paper) => {
                const authors = (paper.authors || []).map((a) => (typeof a === 'string' ? a : a.name)).join(', ');
                return (
                  <div key={paper.id} className="panel" style={{ display: 'flex', flexDirection: 'column', gap: '10px' }}>
                    <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', gap: '16px' }}>
                      <div>
                        <div style={{ fontWeight: 700, fontSize: '1.05rem', color: '#0F172A', lineHeight: 1.35 }}>
                          {paper.title}
                        </div>
                        <div style={{ fontSize: '0.825rem', color: 'var(--text-secondary)', marginTop: '4px' }}>
                          {authors || 'Unknown Authors'} &bull; {paper.venue || 'Corpus'} &bull; {paper.year || 'N/A'} &bull; {paper.citation_count?.toLocaleString() || 0} citations
                        </div>
                      </div>

                      <button
                        className="btn btn-subtle btn-sm"
                        onClick={() => removePaper(paper.id)}
                        title="Remove paper"
                      >
                        <Trash2 size={16} color="var(--color-danger)" />
                      </button>
                    </div>

                    {/* 1-Click Direct Links & Actions */}
                    <div style={{ display: 'flex', flexWrap: 'wrap', gap: '8px', alignItems: 'center', marginTop: '4px' }}>
                      {paper.pdf_url && (
                        <a href={paper.pdf_url} target="_blank" rel="noopener noreferrer" className="btn-pdf">
                          <FileText size={12} />
                          <span>Read PDF</span>
                        </a>
                      )}
                      {paper.doi && (
                        <a href={paper.doi.startsWith('http') ? paper.doi : `https://doi.org/${paper.doi}`} target="_blank" rel="noopener noreferrer" className="btn-doi">
                          <ExternalLink size={12} />
                          <span>Publisher DOI</span>
                        </a>
                      )}
                      {paper.arxiv_id && (
                        <a href={`https://arxiv.org/abs/${paper.arxiv_id}`} target="_blank" rel="noopener noreferrer" className="btn-arxiv">
                          <span>⚛️ arXiv</span>
                        </a>
                      )}
                      <button
                        className="btn btn-outline btn-sm"
                        onClick={() => handleCopyBibtex(paper)}
                        title="Copy BibTeX Citation"
                      >
                        {copiedBibId === paper.id ? <Check size={13} color="var(--color-success)" /> : <Copy size={13} />}
                        <span>{copiedBibId === paper.id ? 'Copied' : 'BibTeX'}</span>
                      </button>
                      <button
                        className="btn btn-subtle btn-sm"
                        onClick={() => setSelectedPaper(paper)}
                      >
                        <span>Details &rarr;</span>
                      </button>
                    </div>
                  </div>
                );
              })}
            </div>
          )}
        </div>
      )}

      {/* Tab 2: Literature Gaps */}
      {activeTab === 'gaps' && (
        <div>
          {savedGaps.length === 0 ? (
            <div className="panel" style={{ textAlign: 'center', padding: '48px 24px' }}>
              <Grid3X3 size={36} color="var(--text-muted)" style={{ margin: '0 auto 12px' }} />
              <h3>No Literature Gaps Saved Yet</h3>
              <p style={{ color: 'var(--text-secondary)', marginTop: '6px', maxWidth: '420px', margin: '6px auto 16px' }}>
                Open the Gap Map on any domain and click the ⭐ icon on high-opportunity cells to save empirical research voids.
              </p>
              <Link to="/" className="btn btn-primary btn-sm">Explore Gap Maps</Link>
            </div>
          ) : (
            <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fill, minmax(320px, 1fr))', gap: '16px' }}>
              {savedGaps.map((gap) => (
                <div key={gap.key} className="panel" style={{ display: 'flex', flexDirection: 'column', justifyContent: 'space-between' }}>
                  <div>
                    <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start' }}>
                      <span className="badge badge-warning" style={{ fontSize: '0.725rem' }}>Research Gap</span>
                      <button
                        className="btn btn-subtle btn-sm"
                        style={{ padding: '2px' }}
                        onClick={() => removeGap(gap.key)}
                        title="Remove gap"
                      >
                        <Trash2 size={15} color="var(--color-danger)" />
                      </button>
                    </div>

                    <h3 style={{ fontSize: '1.05rem', color: '#0F172A', marginTop: '8px' }}>
                      {gap.topicName} &times; {gap.appName}
                    </h3>
                    <div style={{ fontSize: '0.8rem', color: 'var(--accent-indigo)', marginTop: '2px' }}>
                      Domain: {gap.domainName || gap.domainId}
                    </div>

                    <div style={{ display: 'flex', justifyContent: 'space-between', marginTop: '14px', fontSize: '0.825rem', color: 'var(--text-secondary)' }}>
                      <span>Observed: <strong style={{ color: '#0F172A' }}>{gap.observed}</strong></span>
                      <span>Expected: <strong style={{ color: '#0F172A' }}>{gap.expected}</strong></span>
                    </div>

                    <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginTop: '8px' }}>
                      <span style={{ fontSize: '0.8rem', color: '#F59E0B', fontWeight: 600 }}>
                        Score: {(gap.opportunity * 10).toFixed(1)}/10
                      </span>
                      {gap.z_score !== undefined && (
                        <span style={{ fontSize: '0.75rem', color: '#10B981', fontWeight: 600 }}>
                          Z: {gap.z_score}
                        </span>
                      )}
                    </div>
                  </div>

                  <div style={{ marginTop: '16px', paddingTop: '12px', borderTop: '1px solid var(--border-color)' }}>
                    <Link to={`/domain/${gap.domainId}/gap-map`} className="btn btn-outline btn-sm" style={{ width: '100%' }}>
                      <span>View in Gap Map &rarr;</span>
                    </Link>
                  </div>
                </div>
              ))}
            </div>
          )}
        </div>
      )}

      {/* Tab 3: Saved Domains */}
      {activeTab === 'topics' && (
        <div>
          {savedTopics.length === 0 ? (
            <div className="panel" style={{ textAlign: 'center', padding: '48px 24px' }}>
              <Bookmark size={36} color="var(--text-muted)" style={{ margin: '0 auto 12px' }} />
              <h3>No Saved Research Topics</h3>
              <p style={{ color: 'var(--text-secondary)', marginTop: '6px', maxWidth: '420px', margin: '6px auto 16px' }}>
                Save entire domains from the domain header to access their full analytics landscape in 1 click.
              </p>
              <Link to="/" className="btn btn-primary btn-sm">Explore Domains</Link>
            </div>
          ) : (
            <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fill, minmax(300px, 1fr))', gap: '16px' }}>
              {savedTopics.map((topic) => (
                <div key={topic.id} className="panel" style={{ display: 'flex', flexDirection: 'column', justifyContent: 'space-between' }}>
                  <div>
                    <h3 style={{ fontSize: '1.15rem', color: '#0F172A', marginBottom: '6px' }}>{topic.name}</h3>
                    <p style={{ fontSize: '0.85rem', color: 'var(--text-secondary)' }}>
                      Saved on {new Date(topic.savedAt).toLocaleDateString()}
                    </p>
                  </div>
                  <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginTop: '20px' }}>
                    <Link to={`/domain/${topic.id}/landscape`} className="btn btn-outline btn-sm">
                      <span>Open Landscape</span>
                      <ArrowRight size={14} />
                    </Link>
                    <button
                      className="btn btn-subtle btn-sm"
                      onClick={() => removeTopic(topic.id)}
                      title="Remove domain"
                    >
                      <Trash2 size={16} color="var(--color-danger)" />
                    </button>
                  </div>
                </div>
              ))}
            </div>
          )}
        </div>
      )}

      {/* Paper Detail Drawer */}
      <PaperDrawer
        paper={selectedPaper}
        isOpen={Boolean(selectedPaper)}
        onClose={() => setSelectedPaper(null)}
      />
    </div>
  );
}
